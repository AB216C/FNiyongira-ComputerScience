package Chapter2;

public class IntegralVariables {

	public static void main(String[] args) {
		int checking;    //Declare int variable named checking
		byte miles;      //Declare byte variable named miles
		short minutes;   //Declare short variable called minutes
		long diameter;    //Declare a long variable called diameter
		
		
		checking = -20;
		miles = 105;
		minutes = 120;
		diameter = 100000;
		
		System.out.println("We had a journey of " + miles + " miles");
		System.out.println("It took us " + minutes + " minutes");
		System.out.println("The account balance is " + checking);
		System.out.println("The galaxy is "+ diameter +
				" light years in diameter");
		
		

	}

}
